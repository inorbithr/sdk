#!/usr/bin/env python3
"""Generate the terminal themes of `iohr theme` from the InOrbit Mac app (RFC 0212, ADR 0225).

The app's terminal look (its themes, font, cursor) lives in the iohr-mac repository,
`src/lib/term-config.ts` (THEMES, DEFAULTS, fontStack). This file reads it and writes
`cli/crates/iohr/src/commands/theme/themes.json`, the one list `iohr theme`, the
Terminal.app profile and the zsh prompt are made from, the way core's mobile theme is
generated from the web kit's CSS (`dart run tool/theme.dart --check`).

  terminal-themes.py            write themes.json
  terminal-themes.py --check    exit 1 if themes.json differs from the app's themes
  terminal-themes.py --offline  check only that themes.json is whole (no source needed)

The source is read with `git show <ref>:src/lib/term-config.ts` in the iohr-mac checkout
(`--mac DIR`, or $IOHR_MAC_DIR, default ~/development/inorbit/iohr-mac; `--ref`, default
origin/main), so that checkout's files are never touched; `--source FILE` reads a file.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "cli/crates/iohr/src/commands/theme/themes.json"
SOURCE_PATH = "src/lib/term-config.ts"
COLOURS = [
    "background", "foreground", "cursor", "cursorAccent", "selectionBackground",
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
    "brightBlack", "brightRed", "brightGreen", "brightYellow", "brightBlue",
    "brightMagenta", "brightCyan", "brightWhite",
]
HEX = re.compile(r"^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$")


def fail(message):
    print(f"terminal-themes: {message}", file=sys.stderr)
    sys.exit(1)


def object_after(text, at):
    """The `{...}` that starts at text[at] (balanced, strings in this file hold no braces)."""
    if text[at] != "{":
        fail("expected an object")
    depth = 0
    for i in range(at, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[at : i + 1]
    fail("unbalanced braces in the source")


def colours_in(block):
    found = {k: v for k, v in re.findall(r'(\w+):\s*"(#[0-9a-fA-F]{6,8})"', block)}
    missing = [k for k in COLOURS if k not in found]
    if missing:
        fail(f"a theme lacks {', '.join(missing)}")
    return {k: found[k].lower() for k in COLOURS}


def parse(ts):
    """The catalogue from term-config.ts, in the file's order."""
    inorbit = re.search(r"const INORBIT:\s*ITheme\s*=\s*(?=\{)", ts)
    if not inorbit:
        fail("no `const INORBIT: ITheme` in the source")
    inorbit = colours_in(object_after(ts, inorbit.end()))

    start = re.search(r"export const THEMES[^=]*=\s*(?=\{)", ts)
    if not start:
        fail("no `export const THEMES` in the source")
    body = object_after(ts, start.end())
    themes = []
    for m in re.finditer(r'(?:"([a-z][a-z0-9-]*)"|\b([a-z][a-z0-9]*)):\s*\{\s*label:\s*"([^"]+)",\s*dark:\s*(true|false),\s*theme:\s*', body):
        ident, label, dark = m.group(1) or m.group(2), m.group(3), m.group(4) == "true"
        rest = body[m.end() :]
        colours = inorbit if rest.startswith("INORBIT") else colours_in(object_after(rest, 0))
        themes.append({"id": ident, "label": label, "dark": dark, "colors": colours})
    if not themes:
        fail("no theme found in THEMES")

    d = re.search(r"export const DEFAULTS[^=]*=\s*(?=\{)", ts)
    if not d:
        fail("no `export const DEFAULTS` in the source")
    defaults = object_after(ts, d.end())

    def one(pattern, what):
        m = re.search(pattern, defaults)
        if not m:
            fail(f"DEFAULTS has no {what}")
        return m.group(1)

    stack = re.search(r"export const fontStack[^`]*`([^`]*)`", ts)
    if not stack or "${c.fontFamily}" not in stack.group(1):
        fail("no fontStack in the source")
    fallbacks = [p.strip().strip('"') for p in stack.group(1).split("}", 1)[1].split(",")]
    family = one(r'fontFamily:\s*"([^"]+)"', "fontFamily")
    # The stack repeats the default font; the fallbacks are what comes after it.
    fallbacks = [p for p in dict.fromkeys(fallbacks) if p and p not in ("monospace", family)]

    cursor = one(r'cursor:\s*"(bar|block|underline)"', "cursor")
    default_theme = one(r'theme:\s*"([a-z0-9-]+)"', "theme")
    if default_theme not in [t["id"] for t in themes]:
        fail(f"the default theme {default_theme} is not in THEMES")
    return {
        "source": f"iohr-mac {SOURCE_PATH} (THEMES, DEFAULTS, fontStack); generated by tools/terminal-themes.py, do not edit",
        "default": default_theme,
        "font": {
            "family": family,
            "fallbacks": fallbacks,
            "size": float(one(r"fontSize:\s*([0-9.]+)", "fontSize")),
        },
        "cursor": {"style": cursor, "blink": one(r"cursorBlink:\s*(true|false)", "cursorBlink") == "true"},
        "themes": themes,
    }


def whole(catalogue):
    """Every theme has every colour, as hex; the font and cursor are set."""
    problems = []
    if not catalogue.get("themes"):
        problems.append("no themes")
    for t in catalogue.get("themes", []):
        for k in COLOURS:
            if not HEX.match(str(t.get("colors", {}).get(k, ""))):
                problems.append(f"{t.get('id')}: {k} is not a hex colour")
    if catalogue.get("default") not in [t.get("id") for t in catalogue.get("themes", [])]:
        problems.append("the default theme is not listed")
    if not catalogue.get("font", {}).get("family"):
        problems.append("no font")
    return problems


def render(catalogue):
    return json.dumps(catalogue, indent=2) + "\n"


def read_source(args):
    if args.source:
        return Path(args.source).read_text()
    mac = Path(args.mac or os.environ.get("IOHR_MAC_DIR") or "~/development/inorbit/iohr-mac").expanduser()
    if not mac.is_dir():
        fail(f"the Mac app's repository is not at {mac}; pass --mac DIR, set IOHR_MAC_DIR, or use --offline")
    shown = subprocess.run(
        ["git", "-C", str(mac), "show", f"{args.ref}:{SOURCE_PATH}"], capture_output=True, text=True, check=False
    )
    if shown.returncode != 0:
        fail(f"git show {args.ref}:{SOURCE_PATH} failed in {mac}: {shown.stderr.strip()}")
    return shown.stdout


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if themes.json is stale")
    ap.add_argument("--offline", action="store_true", help="only check that themes.json is whole")
    ap.add_argument("--mac", help="the iohr-mac checkout")
    ap.add_argument("--ref", default="origin/main", help="the git ref of the source (default origin/main)")
    ap.add_argument("--source", help="read term-config.ts from this file instead of git")
    args = ap.parse_args()

    if args.offline:
        problems = whole(json.loads(OUT.read_text()))
        if problems:
            fail("; ".join(problems))
        print(f"terminal-themes: {OUT.name} is whole (drift against the app not checked)")
        return 0

    fresh = parse(read_source(args))
    problems = whole(fresh)
    if problems:
        fail("; ".join(problems))
    text = render(fresh)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            fail(f"{OUT} is stale; run `mise run cli:themes` and commit the result")
        print(f"terminal-themes: {len(fresh['themes'])} themes are current with the app")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"terminal-themes: wrote {len(fresh['themes'])} themes to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
