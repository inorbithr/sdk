/// The line every generated file starts with, naming the cuts it was made from.
#[must_use]
pub fn header(api: &iohr_openapi::Api) -> String {
    let cuts: Vec<String> = api
        .profiles
        .iter()
        .map(|(name, cut)| format!("{name}={}", cut.hash))
        .collect();
    format!(
        "Generated by iohr sdk generate for cuts {}; do not edit.",
        cuts.join(", ")
    )
}
