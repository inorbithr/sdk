"""inorbit/ask: a prototype of `iohr ask "<question>"`.

Default backend: the MCP tool `llm_generate` (POST /mcp, JSON-RPC), the only route to the model a
scoped key can use today (`mcp:generate`; no REST scope covers /v1/llm/generate/events). It
returns the whole answer in one result, so nothing streams yet. ASK_BACKEND=generate streams
/v1/llm/generate/events (SSE) and needs a token that holds `iohr.api`, which the extension channel
does not mint for a person profile. ASK_BACKEND=say uses the coordinator instead: it opens a thread, says the question
(`Say`), watches the thread over SSE (`WatchThread`) and prints the reply. Today the coordinator
refuses the keys the extension token channel mints (HTTP 403), so `say` fails until it accepts them. The question and the answer go only to
the API and the terminal: nothing is written to STATE or CACHE and nothing is logged.

    ASK_QUESTION="what is running?" iohr ext dev PATH      # or:  iohr ext dev PATH -- (later)
"""

from __future__ import annotations

import json
import os
import sys
import time
import urllib.error
import urllib.request

from .channel import Refused, token

SCOPES_SAY = ["coordinator:read", "coordinator:write"]
SCOPES_GENERATE = ["mcp:generate", "mcp:read"]
DEADLINE = int(os.environ.get("ASK_TIMEOUT", "180"))
# The edge refuses the default Python-urllib agent (HTTP 403, error 1010).
UA = "iohr-ext-ask/0.1.0"
TERMINAL = {"replied", "failed", "expired", "cancelled"}
LABEL = "AI answer -- generated by an AI model, check it before you rely on it"


def pick(obj: dict, name: str):
    """A field of a protobuf JSON object, in snake_case or lowerCamelCase."""
    camel = "".join(p if i == 0 else p.title() for i, p in enumerate(name.split("_")))
    return obj.get(name, obj.get(camel))


def call(api: str, tok: str, method: str, path: str, body: dict | None = None):
    req = urllib.request.Request(
        api + path,
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"authorization": f"Bearer {tok}", "content-type": "application/json", "user-agent": UA},
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        # The status only: an error body could echo the question.
        raise SystemExit(f"{method} {path.split('?')[0]} -> HTTP {e.code}") from None


def frames(api: str, tok: str, thread: str):
    """Server-sent frames of the thread, each the decoded `data:` JSON."""
    req = urllib.request.Request(
        f"{api}/v1/coordinator/threads/{thread}/events",
        headers={"authorization": f"Bearer {tok}", "accept": "text/event-stream", "user-agent": UA},
    )
    with urllib.request.urlopen(req, timeout=DEADLINE) as r:
        for raw in r:
            line = raw.decode("utf-8", "replace").strip()
            if line.startswith("data:"):
                try:
                    obj = json.loads(line[5:])
                except ValueError:
                    continue
                yield obj.get("result", obj)


def generate(api: str, tok: str, question: str) -> int:
    """Stream llm Generate: one `data:` chunk per piece of text; reasoning chunks are hidden."""
    body = {"messages": [{"role": "user", "content": question}], "tier": "TIER_FAST"}
    req = urllib.request.Request(
        f"{api}/v1/llm/generate/events",
        data=json.dumps(body).encode(),
        method="POST",
        headers={"authorization": f"Bearer {tok}", "content-type": "application/json", "accept": "text/event-stream", "user-agent": UA},
    )
    printed = False
    try:
        with urllib.request.urlopen(req, timeout=DEADLINE) as r:
            event = ""
            for raw in r:
                line = raw.decode("utf-8", "replace").rstrip("\n")
                if line.startswith("event:"):
                    event = line[6:].strip()
                elif line.startswith("data:"):
                    try:
                        c = json.loads(line[5:])
                    except ValueError:
                        continue
                    c = c.get("result", c)
                    if event == "error":
                        print(f"The model could not answer: {c.get('code', '')}", file=sys.stderr)
                        return 1
                    if c.get("reasoning") or c.get("step") or not c.get("text"):
                        continue
                    if not printed:
                        print(f"--- {LABEL} ---", flush=True)
                        printed = True
                    print(c["text"], end="", flush=True)
    except urllib.error.HTTPError as e:
        print(f"POST /v1/llm/generate/events -> HTTP {e.code}", file=sys.stderr)
        return 1
    except (TimeoutError, OSError) as e:
        print(f"stream ended: {type(e).__name__}", file=sys.stderr)
    if printed:
        print("\n--- end of AI answer ---", flush=True)
    return 0 if printed else 1


def mcp(api: str, tok: str, question: str) -> int:
    """MCP `tools/call llm_generate` (stateless streamable HTTP): the answer comes in one result."""
    rpc = {"jsonrpc": "2.0", "id": 1, "method": "tools/call",
           "params": {"name": "llm_generate", "arguments": {"messages": [{"role": "user", "content": question}], "tier": "TIER_FAST", **({"agent": os.environ["ASK_AGENT"]} if os.environ.get("ASK_AGENT") else {})}}}
    req = urllib.request.Request(
        f"{api}/mcp", data=json.dumps(rpc).encode(), method="POST",
        headers={"authorization": f"Bearer {tok}", "content-type": "application/json",
                 "accept": "application/json, text/event-stream", "user-agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=DEADLINE) as r:
            raw = r.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        print(f"POST /mcp llm_generate -> HTTP {e.code}", file=sys.stderr)
        return 1
    # The answer is JSON, or one SSE `data:` frame holding it.
    body = next((l[5:] for l in raw.splitlines() if l.startswith("data:")), raw)
    try:
        out = json.loads(body)
    except ValueError:
        print("unreadable MCP answer", file=sys.stderr)
        return 1
    if "error" in out or out.get("result", {}).get("isError"):
        print("The model could not answer: the tool refused", file=sys.stderr)
        return 1
    result = out.get("result", {})
    text = ""
    sc = result.get("structuredContent")
    if isinstance(sc, dict):
        text = sc.get("text") or "".join(c.get("text", "") for c in sc.get("chunks", []) if not c.get("reasoning"))
    if not text:
        for c in result.get("content", []):
            part = c.get("text", "") if c.get("type") == "text" else ""
            try:  # the tool puts its JSON answer in a text block
                part = json.loads(part).get("text", part)
            except (ValueError, AttributeError):
                pass
            text += part
    print(f"--- {LABEL} ---", flush=True)
    print(text, flush=True)
    print("--- end of AI answer ---", flush=True)
    return 0


def main() -> int:
    question = " ".join(sys.argv[1:]).strip() or os.environ.get("ASK_QUESTION", "").strip()
    if not question:
        print('give a question: ASK_QUESTION="..." iohr ext dev PATH', file=sys.stderr)
        return 2
    api = os.environ.get("IOHR_EXT_API", "").rstrip("/")
    if not api:
        print("IOHR_EXT_API is not set: run this with iohr ext dev", file=sys.stderr)
        return 2
    backend = os.environ.get("ASK_BACKEND", "mcp")
    say = backend == "say"
    try:
        # ASK_TEST_TOKEN: the self-test's fake API needs no real token; never set outside tests.
        tok = os.environ.get("ASK_TEST_TOKEN") if os.environ.get("IOHR_EXT_API", "").startswith("http://127.0.0.1") and os.environ.get("ASK_TEST_TOKEN") else token(SCOPES_SAY if say else SCOPES_GENERATE)
    except Refused as e:
        print(f"token refused: {e}", file=sys.stderr)
        return 1
    if backend == "generate":
        return generate(api, tok, question)
    if not say:
        return mcp(api, tok, question)

    # The title and purpose are fixed text: the question is only ever the message body.
    made = call(api, tok, "POST", "/v1/coordinator/threads", {"title": "iohr ask", "purpose": "A question from the terminal."})
    thread = pick(pick(made, "thread") or {}, "thread_id")
    if not thread:
        print("the coordinator returned no thread", file=sys.stderr)
        return 1
    said = call(api, tok, "POST", f"/v1/coordinator/threads/{thread}/messages", {"body": question})
    mine = pick(pick(said, "message") or {}, "message_id")

    started = time.monotonic()
    printed = False
    settled = None
    code = 1
    try:
        for f in frames(api, tok, thread):
            m = f.get("message")
            if m and pick(m, "message_id") != mine and m.get("kind") != "say":
                if not printed:
                    print(f"--- {LABEL} ---", flush=True)
                    printed = True
                print(m.get("body", ""), flush=True)
                code = 0
                if settled:
                    break
            t = f.get("turn")
            if t and t.get("state") in TERMINAL:
                settled = t["state"]
                if printed or settled != "replied":
                    if settled != "replied" and not printed:
                        print(f"The model did not answer: the turn {settled} (outcome {t.get('outcome', '')})", file=sys.stderr)
                    break
            if time.monotonic() - started > DEADLINE:
                print("no answer in time", file=sys.stderr)
                break
    except (TimeoutError, OSError) as e:
        print(f"stream ended: {type(e).__name__}", file=sys.stderr)
    if printed:
        print("--- end of AI answer ---", flush=True)
    try:
        call(api, tok, "POST", f"/v1/coordinator/threads/{thread}/close", {})
    except SystemExit:
        pass
    return code


if __name__ == "__main__":
    sys.exit(main())
