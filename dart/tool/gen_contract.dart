// Writes lib/src/generated/contract.g.dart from ../spec/openapi.json: every
// operation's successful JSON answer and the schemas those answers reach, nothing
// else. `mise run dart:gen` runs it; CI fails when the committed file differs.
//
// Usage: dart run tool/gen_contract.dart [--spec PATH] [--out PATH]

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  var specPath = '../spec/openapi.json';
  var outPath = 'lib/src/generated/contract.g.dart';
  for (var i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--spec':
        specPath = args[++i];
      case '--out':
        outPath = args[++i];
      default:
        stderr.writeln('unknown argument ${args[i]}');
        exit(2);
    }
  }

  final spec =
      jsonDecode(File(specPath).readAsStringSync()) as Map<String, Object?>;
  final info = spec['info']! as Map<String, Object?>;
  final paths = spec['paths']! as Map<String, Object?>;
  final schemas =
      (spec['components']! as Map<String, Object?>)['schemas']!
          as Map<String, Object?>;

  const methods = ['get', 'post', 'put', 'patch', 'delete'];
  final operations = <Map<String, Object?>>[];
  final reached = <String>{};

  void reach(Object? node) {
    if (node is Map) {
      final ref = node[r'$ref'];
      if (ref is String) {
        final name = ref.split('/').last;
        if (reached.add(name)) reach(schemas[name]);
      }
      node.values.forEach(reach);
    } else if (node is List) {
      node.forEach(reach);
    }
  }

  for (final path in paths.keys.toList()..sort()) {
    final item = paths[path]! as Map<String, Object?>;
    for (final method in methods) {
      final op = item[method];
      if (op is! Map<String, Object?>) continue;
      final answers = <String, Object?>{};
      final responses = op['responses'] as Map<String, Object?>? ?? const {};
      for (final status in responses.keys.toList()..sort()) {
        if (!status.startsWith('2')) continue;
        final content =
            (responses[status]! as Map<String, Object?>)['content']
                as Map<String, Object?>?;
        final json = content?['application/json'] as Map<String, Object?>?;
        final schema = json?['schema'];
        if (schema == null) continue;
        answers[status] = schema;
        reach(schema);
      }
      operations.add({
        'id': op['operationId'] ?? '${method.toUpperCase()} $path',
        'method': method.toUpperCase(),
        'path': path,
        'answers': answers,
      });
    }
  }

  final contract = {
    'api_version': info['version'],
    'operations': operations,
    'schemas': {
      for (final name in reached.toList()..sort()) name: schemas[name],
    },
  };
  final text = jsonEncode(_sorted(contract));
  if (text.contains("'''")) {
    stderr.writeln('the contract holds three quotes in a row; cannot embed it');
    exit(1);
  }
  File(outPath)
    ..createSync(recursive: true)
    ..writeAsStringSync('''
// GENERATED by tool/gen_contract.dart from spec/openapi.json. Do not edit.
// ${operations.length} operations, ${reached.length} schemas.

/// The API version the contract was taken from.
const String contractApiVersion = '${info['version']}';

/// Every operation's successful answer and the schemas it reaches, as JSON.
const String contractJson = r\'\'\'$text\'\'\';
''');
  stdout.writeln(
    'wrote $outPath: ${operations.length} operations, ${reached.length} schemas',
  );
}

/// Map keys in order, so the same spec always gives the same file.
Object? _sorted(Object? node) => switch (node) {
  final Map<Object?, Object?> m => {
    for (final k in m.keys.map((k) => k.toString()).toList()..sort())
      k: _sorted(m[k]),
  },
  final List<Object?> l => [for (final v in l) _sorted(v)],
  _ => node,
};
